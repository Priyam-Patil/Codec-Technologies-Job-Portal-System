import { test, expect } from '@playwright/test';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { randomBytes } from 'node:crypto';
import mongoose from 'mongoose';
import { signInCandidate, signedRequest } from './browser-helpers.js';

const root = fileURLToPath(new URL('../../', import.meta.url));
const api = 'http://127.0.0.1:5000';
const frontend = 'http://127.0.0.1:5175';
test.skip(process.env.JOB_PORTAL_AUDIT !== '1', 'Run the full audit config with the explicit persistent local development server');

test('normal application: real registration, unseeded candidate, resume edge cases and persisted workflow', async ({ browser }, info) => {
  test.setTimeout(180000);
  const health = await fetch(api + '/health');
  expect(health.headers.get('x-insiderjobs-mode')).toBe('local-development');
  const session = JSON.parse(await fs.readFile(path.join(root, '.qa/audit-session.json')));
  const local = JSON.parse(await fs.readFile(path.join(root, '.qa/local-session.json')));
  if (!local.mongoUri.startsWith('mongodb://127.0.0.1:') || !local.mongoUri.endsWith('/insiderjobs_development')) throw new Error('Persistent tests require the guarded localhost database');
  const account = session.users.find(user => user.viewport === info.project.name);
  const email = `audit-${Date.now()}-${info.project.name}@example.test`;
  const password = randomBytes(20).toString('base64url') + '!Aa7';
  // Ignored local credentials allow the owner to inspect the persisted test recruiter without logging secrets.
  await fs.writeFile(path.join(root, `.qa/local-recruiter-${info.project.name}.json`), JSON.stringify({ email, password }));
  const employerContext = await browser.newContext(info.project.use);
  const personContext = await browser.newContext(info.project.use);
  const employer = await employerContext.newPage(), person = await personContext.newPage();
  const pageErrors = [];
  for (const page of [employer, person]) page.on('pageerror', error => pageErrors.push(error.message));
  const title = `Persistent ${info.project.name} ${Date.now()}`;
  try {
    await employer.goto(frontend);
    await employer.getByRole('button', { name: 'Recruiter Login', exact: true }).click();
    await employer.getByRole('button', { name: 'Sign up', exact: true }).click();
    await employer.getByLabel('Company name', { exact: true }).fill('Audit Development Company');
    try { await employer.getByLabel('Recruiter email', { exact: true }).fill(email); await employer.getByLabel('Recruiter password', { exact: true }).fill(password); }
    catch { throw new Error('Registration credentials input unavailable; details suppressed'); }
    await employer.getByRole('button', { name: 'View', exact: true }).click();
    await expect(employer.getByLabel('Recruiter password')).toHaveAttribute('type', 'text');
    await employer.getByRole('button', { name: 'Hide', exact: true }).click();
    await employer.getByRole('dialog').getByRole('button', { name: 'Next', exact: true }).click();
    await employer.getByRole('button', { name: 'Create Account', exact: true }).click();
    await expect(employer.getByText('Please upload company logo', { exact: true })).toBeVisible();
    await employer.getByLabel('Company logo').setInputFiles(path.join(root, 'client/src/assets/adobe_logo.png'));
    await employer.getByRole('button', { name: 'Create Account', exact: true }).click();
    if (await employer.getByLabel('Recruiter password').isVisible()) await employer.getByLabel('Recruiter password').fill('').catch(() => {});
    await expect(employer.getByRole('heading', { name: 'Manage Jobs', exact: true })).toBeVisible({ timeout: 30000 });
    await employer.getByRole('link', { name: 'Analytics', exact: true }).click();
    await expect(employer.getByText('No jobs posted yet. Add your first job to begin.', { exact: true })).toBeVisible();
    await employer.getByRole('link', { name: 'Add Job', exact: true }).click();
    await employer.getByRole('button', { name: 'ADD', exact: true }).click();
    expect(await employer.getByLabel('Job Title', { exact: true }).evaluate(input => input.validity.valueMissing)).toBeTruthy();
    await employer.getByLabel('Job Title', { exact: true }).fill(title);
    await employer.locator('.ql-editor').fill('React, Node.js, MongoDB and Kubernetes. Build accessible applications.');
    await employer.getByLabel('Job Salary', { exact: true }).fill('2000000');
    await employer.getByRole('button', { name: 'ADD', exact: true }).click();
    await expect(employer.getByText('Job posted successfully', { exact: true })).toBeVisible();
    await employer.reload();
    await employer.getByRole('link', { name: 'Manage Jobs', exact: true }).click();
    await expect(employer.getByRole('row').filter({ hasText: title })).toBeVisible();
    const db = await mongoose.createConnection(local.mongoUri, { autoIndex: false, autoCreate: false }).asPromise();
    const job = await db.db.collection('jobs').findOne({ title });
    expect(job).toBeTruthy();
    await db.close();

    await person.goto(frontend);
    await signInCandidate(person, account);
    const initial = await signedRequest(person, api, '/api/users/user');
    expect(initial.status).toBe(200);
    const fixtureDb = await mongoose.createConnection(local.mongoUri, { autoIndex: false, autoCreate: false }).asPromise();
    await fixtureDb.db.collection('users').updateOne({ _id: account.id, email: account.email }, { $set: { resume: '', resumeAsset: {}, resumeAnalysis: {} } });
    await fixtureDb.close();
    await signedRequest(person, api, '/api/users/profile', 'PUT', { skills: [] });
    await person.goto(frontend + '/applications');
    await expect(person.locator('#resumeUpload')).toBeAttached();
    await person.goto(frontend + '/apply-job/' + job._id);
    await person.getByRole('button', { name: 'Apply Now', exact: true }).first().click();
    await expect(person.getByText('Upload resume to apply', { exact: true })).toBeVisible();
    await expect(person.getByRole('heading', { name: 'Your Resume', exact: true })).toBeVisible();
    const file = person.locator('#resumeUpload');
    await file.setInputFiles({ name: 'resume.html', mimeType: 'text/html', buffer: Buffer.from('<script>bad</script>') });
    await person.getByRole('button', { name: 'Save', exact: true }).click();
    await expect(person.getByText('Choose a PDF no larger than 5 MB', { exact: true }).first()).toBeVisible();
    await file.setInputFiles({ name: 'oversized.pdf', mimeType: 'application/pdf', buffer: Buffer.alloc(5 * 1024 * 1024 + 1) });
    await person.getByRole('button', { name: 'Save', exact: true }).click();
    await expect(person.getByText('Choose a PDF no larger than 5 MB', { exact: true }).first()).toBeVisible();
    await file.setInputFiles({ name: 'damaged.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.7 invalid content') });
    await person.getByRole('button', { name: 'Save', exact: true }).click();
    await expect(person.getByText(/This PDF is damaged or password-protected/)).toBeVisible({ timeout: 30000 });
    await file.setInputFiles(path.join(root, 'server/e2e/fixtures/resume.pdf'));
    await person.getByRole('button', { name: 'Save', exact: true }).click();
    const analysis = person.getByRole('region', { name: 'Resume analysis summary' });
    await expect(analysis.getByText('React', { exact: true })).toBeVisible({ timeout: 30000 });
    await expect(analysis.getByText(/Experience mention: 2 years/)).toBeVisible();
    await person.reload();
    await expect(person.getByRole('region', { name: 'Resume analysis summary' }).getByText('MongoDB', { exact: true })).toBeVisible();
    await person.getByRole('link', { name: 'Compare skills and find matching jobs', exact: true }).click();
    await person.getByLabel('Compare with a job', { exact: true }).selectOption(String(job._id));
    await expect(person.getByText('Missing: Kubernetes', { exact: true })).toBeVisible();
    await expect(person.getByRole('heading', { name: /75% skill coverage/ })).toBeVisible();
    await person.goto(frontend + '/apply-job/' + job._id);
    await person.getByRole('button', { name: 'Apply Now', exact: true }).first().click();
    await expect(person.getByRole('button', { name: 'Already Applied', exact: true }).first()).toBeDisabled();
    await person.goto(frontend);
    await person.getByLabel('Hide jobs I applied to', { exact: true }).check();
    await expect(person.getByRole('heading', { name: title, exact: true })).toHaveCount(0);
    await person.getByRole('button', { name: 'Clear filters', exact: true }).click();
    await expect(person.getByRole('heading', { name: title, exact: true })).toBeVisible();
    await employer.getByRole('link', { name: 'View Applications', exact: true }).click();
    await employer.getByLabel('Application status', { exact: true }).selectOption('Rejected');
    await expect(employer.getByText('Application Rejected', { exact: true })).toBeVisible();
    await employer.reload();
    await expect(employer.getByLabel('Application status')).toHaveValue('Rejected');
    await person.getByRole('link', { name: 'Applied Jobs', exact: true }).click();
    await expect(person.getByText('Rejected', { exact: true }).filter({ visible: true }).first()).toBeVisible();
    await person.screenshot({ path: path.join(root, `docs/screenshots/final-normal-${info.project.name}.png`), fullPage: true });
    await employer.getByRole('button', { name: 'Logout', exact: true }).click();
    await expect(employer.getByRole('button', { name: 'Recruiter Login', exact: true })).toBeVisible();
    expect(pageErrors).toEqual([]);
  } finally { await personContext.close(); await employerContext.close(); }
});
